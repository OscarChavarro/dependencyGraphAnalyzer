package backend.application.service;

import backend.domain.model.LfsBuildGuideEntryModel;
import backend.domain.model.LfsBuildGuideModel;
import backend.domain.model.LfsBuildStepModel;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;
import org.springframework.stereotype.Component;

/** Renders the AGENTS.md build guide (English Markdown) for an AI agent driving the LFS build. */
@Component
public class LfsBuildGuideRenderer {
    private static final DateTimeFormatter TIMESTAMP = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    public String render(LfsBuildGuideModel guide) {
        StringBuilder md = new StringBuilder();
        line(md, "# AGENTS.md - Linux From Scratch build guide");
        line(md, "");
        line(md, "Generated by dependencyGraphAnalyzer (\"Compute LFS\") on " + guide.generatedAt().format(TIMESTAMP)
                + " for project `" + guide.projectId() + "`. Regenerated on every run: do not edit by hand;"
                + " keep your own notes in `BUILD_STATUS.md`.");
        line(md, "");
        line(md, "This folder holds Debian/Ubuntu source packages downloaded with `apt-get source`. You are an AI"
                + " agent in charge of building them. This file is your contract: it gives the build order and the"
                + " rules to follow.");
        line(md, "");
        line(md, "- Source packages to build: **" + guide.steps().size() + "**");
        line(md, "- Selected binary packages: **" + guide.steps().stream().mapToInt(s -> s.selectedPackages().size()).sum()
                + "**");
        if (!guide.failedPackages().isEmpty()) {
            line(md, "- Packages whose source could not be downloaded: **" + guide.failedPackages().size()
                    + "** (see the last section)");
        }
        line(md, "");

        renderRules(md);
        renderProcedure(md);
        renderExtraDebs(md);
        renderStatusFile(md);
        renderOrderTable(md, guide.steps());
        renderStepDetails(md, guide.steps());
        renderFailed(md, guide.failedPackages());
        return md.toString();
    }

    private static void renderRules(StringBuilder md) {
        line(md, "## Ground rules");
        line(md, "");
        line(md, "1. **Follow the build order strictly.** Steps go from sinks to sources of the dependency graph"
                + " (from the simplest group to the most composite one, and the same inside each group): a step only"
                + " depends on earlier steps or on the base system. Do not start step N+1 until step N is built and"
                + " its selected packages are installed.");
        line(md, "2. **Use every available CPU core.** Every `make` must run as `make -j\"$(nproc)\"`. Debian builds"
                + " must run with `DEB_BUILD_OPTIONS=\"parallel=$(nproc)\"` and `dpkg-buildpackage -j\"$(nproc)\"`."
                + " Never hard-code a job count. Only if a package fails in parallel and the log suggests a race,"
                + " retry that single package once with `-j1` and write it down in `BUILD_STATUS.md`.");
        line(md, "3. **Stay inside this folder.** Do not delete or modify the downloaded files (`*.dsc`, `*.orig.tar.*`,"
                + " `*.debian.tar.*`). Patches you need go in the source directory's `debian/patches/` and must be"
                + " recorded in `BUILD_STATUS.md`.");
        line(md, "4. **Do not download sources again.** Every source listed below is already unpacked here. Run"
                + " `apt-get source` only for a package listed under \"Sources not downloaded\".");
        line(md, "5. **Never skip a failed step silently.** Later steps depend on it. Try to fix it (missing build"
                + " dependency, `-j1` retry); if you cannot, stop and report to the human with the log excerpt.");
        line(md, "6. **Be resumable.** Update `BUILD_STATUS.md` after every step, so the process can be stopped and"
                + " resumed at any time. On start, read it and continue from the first step not marked `built`.");
        line(md, "");
    }

    private static void renderProcedure(StringBuilder md) {
        line(md, "## How to build one step");
        line(md, "");
        line(md, "Run from this folder (`STEP` is the zero-padded step number, `SRC` the source package, `DIR` its"
                + " directory, all taken from the build order table):");
        line(md, "");
        line(md, "```sh");
        line(md, "mkdir -p logs debs");
        line(md, "cd \"$DIR\"");
        line(md, "# 1. Build dependencies: packages built in earlier steps are already installed; get the rest.");
        line(md, "sudo apt-get build-dep -y ./");
        line(md, "# 2. Build binary packages with all cores.");
        line(md, "export DEB_BUILD_OPTIONS=\"parallel=$(nproc) nocheck\"");
        line(md, "dpkg-buildpackage -us -uc -b -j\"$(nproc)\" 2>&1 | tee \"../logs/$STEP-$SRC.log\"");
        line(md, "test \"${PIPESTATUS[0]}\" -eq 0");
        line(md, "cd ..");
        line(md, "# 3. Collect every artifact the build produced.");
        line(md, "mkdir -p \"debs/$STEP-$SRC\"");
        line(md, "mv -- *.deb *.ddeb *.udeb *.buildinfo *.changes \"debs/$STEP-$SRC/\" 2>/dev/null || true");
        line(md, "# 4. Install the selected binary packages of this step (see \"Extra .deb files\").");
        line(md, "```");
        line(md, "");
        line(md, "Drop `nocheck` only when the human asks for test suites to run. If a package is built by hand"
                + " instead of through Debian packaging (LFS style), use the same rule:"
                + " `./configure --prefix=/usr && make -j\"$(nproc)\" && make DESTDIR=\"$PWD/../stage/$SRC\" install`.");
        line(md, "");
    }

    private static void renderExtraDebs(StringBuilder md) {
        line(md, "## Extra .deb files");
        line(md, "");
        line(md, "A source package usually builds **more binary packages than the ones that were selected**"
                + " (`-dev`, `-doc`, `-dbgsym`, libraries for other ABIs, udebs, ...). Each step below lists both the"
                + " selected binary packages and every binary the source can produce.");
        line(md, "");
        line(md, "- Keep every produced artifact in `debs/STEP-SRC/`; never delete them.");
        line(md, "- After a step, install **only** its selected binary packages, e.g."
                + " `sudo apt-get install -y ./debs/STEP-SRC/NAME_*.deb` (one per selected package that was built).");
        line(md, "- Also install an extra produced package when a later step lists it in its Build-Depends.");
        line(md, "- Do not install `-dbgsym`/`.ddeb`, `.udeb` or packages of other architectures unless asked.");
        line(md, "- A selected package that the build did not produce (for instance it belongs to another"
                + " architecture or build profile) must be written down in `BUILD_STATUS.md` as `not produced`.");
        line(md, "- Write in `BUILD_STATUS.md` the list of extra packages each step produced.");
        line(md, "");
    }

    private static void renderStatusFile(StringBuilder md) {
        line(md, "## BUILD_STATUS.md");
        line(md, "");
        line(md, "Create it from the build order table if it does not exist, with one row per step:");
        line(md, "");
        line(md, "```markdown");
        line(md, "| Step | Source | Status | Installed | Extra debs | Notes |");
        line(md, "|------|--------|--------|-----------|------------|-------|");
        line(md, "| 001  | zlib   | built  | zlib1g    | zlib1g-dev, lib32z1 | |");
        line(md, "```");
        line(md, "");
        line(md, "Status is one of `pending`, `building`, `built`, `failed`, `blocked`. Mark `building` before"
                + " starting a step, so an interrupted step is rebuilt on resume.");
        line(md, "");
    }

    private static void renderOrderTable(StringBuilder md, List<LfsBuildStepModel> steps) {
        line(md, "## Build order");
        line(md, "");
        if (steps.isEmpty()) {
            line(md, "Nothing to build: no source was downloaded.");
            line(md, "");
            return;
        }
        line(md, "| Step | Source package | Version | Directory | Group | Selected binary packages |");
        line(md, "|------|----------------|---------|-----------|-------|--------------------------|");
        for (LfsBuildStepModel step : steps) {
            line(md, "| " + stepNumber(step) + " | `" + step.sourcePackage() + "` | " + step.sourceVersion()
                    + " | `" + step.directoryName() + "/`" + (step.directoryPresent() ? "" : " (missing)")
                    + " | " + joinOrDash(step.groups()) + " | " + String.join(", ", step.selectedPackages()) + " |");
        }
        line(md, "");
    }

    private static void renderStepDetails(StringBuilder md, List<LfsBuildStepModel> steps) {
        if (steps.isEmpty()) {
            return;
        }
        line(md, "## Steps in detail");
        line(md, "");
        for (LfsBuildStepModel step : steps) {
            line(md, "### " + stepNumber(step) + " - " + step.sourcePackage() + " " + step.sourceVersion());
            line(md, "");
            line(md, "- Directory: `" + step.directoryName() + "/`"
                    + (step.directoryPresent() ? "" : " - **not found: run `apt-get source " + step.sourcePackage()
                    + "` first**"));
            line(md, "- Group: " + joinOrDash(step.groups()));
            line(md, "- Selected binary packages (install after building): " + String.join(", ", step.selectedPackages()));
            line(md, "- All binary packages this source produces: " + joinOrDash(step.producedBinaries()));
            line(md, "- Build-Depends: " + (step.buildDepends().isBlank() ? "-" : step.buildDepends()));
            line(md, "");
        }
    }

    private static void renderFailed(StringBuilder md, List<LfsBuildGuideEntryModel> failed) {
        if (failed.isEmpty()) {
            return;
        }
        line(md, "## Sources not downloaded");
        line(md, "");
        line(md, "`apt-get source` failed for these packages. They are not in the build order. Before building any"
                + " step that needs them, try `apt-get source NAME` again (check `apt-get-source.log`); if it still"
                + " fails, report it to the human.");
        line(md, "");
        for (LfsBuildGuideEntryModel entry : failed) {
            String reason = entry.message() == null || entry.message().isBlank()
                    ? ""
                    : ": " + entry.message().lines().reduce((first, second) -> second).orElse("").trim();
            line(md, "- `" + entry.packageName() + "`" + (entry.groupName() == null ? "" : " [" + entry.groupName() + "]")
                    + reason);
        }
        line(md, "");
    }

    private static String stepNumber(LfsBuildStepModel step) {
        return String.format(Locale.ROOT, "%03d", step.step());
    }

    private static String joinOrDash(List<String> values) {
        return values.isEmpty() ? "-" : String.join(", ", values);
    }

    private static void line(StringBuilder md, String text) {
        md.append(text).append('\n');
    }
}
